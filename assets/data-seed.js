/* Regroupe tout au format "un point d'historique par titre", pour que
   drive-client.js et data-seed.js aient exactement la même forme,
   qu'on lise depuis Drive ou depuis ce fichier de secours. */
function buildSeedHistory() {
  const actions = {};
  SEED_ACTIONS.forEach(r => {
    const [code, nom, cours, variation, nbTitres, capFlott, capGlob, capGlobPct, volTitres, volValeur, per, volValeurPct] = r;
    actions[code] = {
      nom, type: "action",
      history: [{ date: SEED_DATE, cours, variation, nbTitres, capFlott, capGlob, capGlobPct, volTitres, volValeur, per, volValeurPct }]
    };
  });

  const obligations = {};
  SEED_OBLIGATIONS.forEach(r => {
    const [code, nom, dateEmission, cours, couponCouru, dpDate, dpValeur] = r;
    obligations[code] = {
      nom, type: "obligation", dateEmission,
      history: [{ date: SEED_DATE, cours, couponCouru, dernierPaiementDate: dpDate, dernierPaiementValeur: dpValeur }]
    };
  });

  const indices = {};
  SEED_INDICES.forEach(r => {
    const [code, nom, cloturePrec, cloture, variation, ytd, categorie] = r;
    indices[code] = {
      nom, categorie,
      history: [{ date: SEED_DATE, cloturePrec, cloture, variation, ytd }]
    };
  });

  return { updated: SEED_DATE + "T" + SEED_MARKET.heure, actions, obligations, indices, market: SEED_MARKET };
}

window.BRVM_SEED = buildSeedHistory();
